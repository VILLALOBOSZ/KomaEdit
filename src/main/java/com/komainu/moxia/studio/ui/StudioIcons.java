    private StudioIcons() {
    }

    private static void mask(Icon icon, String... rows) {
        String[] full = new String[SIZE];
        for (int row = 0; row < SIZE; row++) {
            String line = row < rows.length ? rows[row] : "";
            if (line.length() > SIZE) {
                throw new IllegalStateException(icon + " fila " + row + " mide " + line.length());
            }
            full[row] = line + ".".repeat(SIZE - line.length());
        }
        MASKS.put(icon, full);
    }

    /** La rejilla de un icono (12 filas de 12 caracteres), para las pruebas. */
    public static String[] mask(Icon icon) {
        return MASKS.get(icon).clone();
    }

    /** Dibuja {@code icon} con la esquina superior izquierda en ({@code x}, {@code y}). */
    public static void draw(StudioCanvas canvas, Icon icon, int x, int y, int color) {
        draw(canvas, icon, x, y, color, 1);
    }

    /** Dibuja {@code icon} a {@code scale} píxeles por píxel del icono. */
    public static void draw(StudioCanvas canvas, Icon icon, int x, int y, int color, int scale) {
        String[] rows = MASKS.get(icon);
        for (int row = 0; row < SIZE; row++) {
            String line = rows[row];
            int column = 0;
            while (column < SIZE) {
                char symbol = line.charAt(column);
                int end = column + 1;
                while (end < SIZE && line.charAt(end) == symbol) {
                    end++;
                }
                if (symbol != '.') {
                    canvas.fill(new Rect(x + column * scale, y + row * scale, (end - column) * scale, scale),
                            color(symbol, color));
                }
                column = end;
            }
        }
    }

    private static int color(char symbol, int color) {
        return switch (symbol) {
            case '+' -> StudioTheme.fade(color, 0.5);
            case 'r' -> 0xFFE24B6A;
            case 'y' -> 0xFFF2B94B;
            case 'b' -> 0xFF4BC3E2;
            case 'x' -> StudioTheme.DANGER;
            default -> color;
        };
    }
